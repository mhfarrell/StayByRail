def get_cities():
    return list(LINES.keys())


def get_lines(city):
    city_data = LINES.get(city, {})
    # Sort by popularity (lower = more important)
    sorted_lines = sorted(city_data.items(), key=lambda x: x[1].get("popularity", 99))
    return {key: val["name"] for key, val in sorted_lines}


def get_stations(city, line, popular_only=True):
    line_data = LINES.get(city, {}).get(line)
    if not line_data:
        return []
    stations = line_data["stations"]
    if popular_only:
        stations = [s for s in stations if s["popular"]]
    return stations
